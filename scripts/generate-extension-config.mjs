import { config as loadEnv } from 'dotenv';
import { mkdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

loadEnv({ path: '.env' });
loadEnv({ path: '.env.local', override: true });

const supabaseUrl = process.env.EXTENSION_SUPABASE_URL || process.env.VITE_SUPABASE_URL || '';
const supabaseAnonKey = process.env.EXTENSION_SUPABASE_ANON_KEY || process.env.VITE_SUPABASE_ANON_KEY || '';

const outPath = resolve('browser-extension', 'config.js');
mkdirSync(resolve('browser-extension'), { recursive: true });

const fileContent = `'use strict';\n\n// Auto-generated by: npm run extension:config\n// Do not edit manually.\n\nglobalThis.REDLINE_EXTENSION_CONFIG = Object.freeze({\n  supabaseUrl: ${JSON.stringify(supabaseUrl)},\n  supabaseAnonKey: ${JSON.stringify(supabaseAnonKey)},\n});\n`;

writeFileSync(outPath, fileContent, 'utf8');

if (!supabaseUrl || !supabaseAnonKey) {
  console.warn('[extension:config] Missing Supabase extension variables. Fill EXTENSION_SUPABASE_URL and EXTENSION_SUPABASE_ANON_KEY (or VITE_* equivalents) in .env/.env.local.');
} else {
  console.log('[extension:config] Generated browser-extension/config.js successfully.');
}
